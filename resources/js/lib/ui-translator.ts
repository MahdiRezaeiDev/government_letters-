export function translateInterfaceText(text: string, locale: SupportedLocale): string {
    if (locale !== 'ps' || !/[\u0600-\u06ff]/u.test(text)) return text;

    const leading = text.match(/^\s*/u)?.[0] ?? '';
    const trailing = text.match(/\s*$/u)?.[0] ?? '';
    const core = text.trim();

    if (exactPashto[core]) return leading + exactPashto[core] + trailing;

    const translated = core
        .replace(/[\u0600-\u06ff\u200c]+/gu, (word) => pashtoWords[word] ?? word)
        .replace(/\s{2,}/gu, ' ')
        .replace(/\s+([،؛؟,.!])/gu, '$1');

    return leading + translated + trailing;
}

export function installInterfaceTranslator(): void {
    const target = globalThis as typeof globalThis & {
        __appLocale?: SupportedLocale;
        __uiTranslate?: (text: string) => string;
    };

    target.__appLocale = (document.documentElement.lang || 'fa').split('-')[0] as SupportedLocale;
    target.__uiTranslate = (text: string) => translateInterfaceText(text, target.__appLocale ?? 'fa');
}
